#include <bits/stdc++.h>
using namespace std;

// ── dbg 的本體。三行而已 ──────────────────────────────────
//  在 CLion Debug  : LOCAL 有定義 -> dbg(x) 會印東西
//  在 Codeforces   : LOCAL 沒定義 -> dbg(x) 變成空的,整行消失
#ifdef LOCAL
    #define dbg(x) cerr << #x << " = " << (x) << endl
#else
    #define dbg(x)
#endif

void solve() {
    int n;
    cin >> n;
//想知道xx是甚麼就放他後面
    dbg(n);          // ★ 就是這一行。它會印出 "n = 幾"

    long long sum = 0;
    for (int i = 0; i < n; i++) {
        int x;
        cin >> x;
        sum += x;
    }

    cout << sum << "\n";     // ← 這是答案,用 cout
}

int main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    int t = 1;
    cin >> t;        // 🔴 BUG 就在這行!這題是單筆測資,這行應該註解掉
    while (t--) solve();
    return 0;
}

